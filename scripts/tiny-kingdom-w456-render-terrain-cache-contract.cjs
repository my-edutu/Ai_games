'use strict';
// W456 Phase-1 RED/GREEN contract for the real seasonal terrain, road,
// farm and occupied-home cold builder. This does not measure physical FPS.
const assert=require('node:assert/strict');
const fs=require('node:fs'),vm=require('node:vm');
const html=fs.readFileSync('public/tiny-kingdom/index.html','utf8');
const start=html.indexOf('<script>'),end=html.lastIndexOf('</script>');
assert(start>0&&end>start,'real original playable script must exist');
const source=html.slice(start+8,end);
new vm.Script(source);
assert.match(source,/const STATIC_TERRAIN_MEMO_LIMIT=32768/);
assert.match(source,/function terrain\(x,z\)/);
assert.match(source,/exactNumericCoordinateKeys:true/);
assert.match(source,/fullFlushOnCapacity:false/);
assert.match(source,/staticTerrainMemoPairs>=STATIC_TERRAIN_MEMO_LIMIT/);
const begin=source.indexOf('const STATIC_TERRAIN_MEMO_LIMIT=32768;');
const finish=source.indexOf('// Continuous grass vertex colours',begin);
assert(begin>0&&finish>begin);
const helper=source.slice(begin,finish);
const factory=new Function('rawTerrain',
 'let presentationEpoch=0,lastFrozenFrameKey=null;\n'+helper+
 'return {read:terrain,activate:value=>staticTerrainMemoActive=value,'+
 'override:setStaticTerrainMemoEnabledForTesting,audit:getStaticTerrainMemoAudit};');
let evaluations=0;
const raw=(x,z)=>{evaluations++;return x*.17+z*.13+Math.sin(x*.31-z*.47)};
const memo=factory(raw);
assert.equal(memo.audit().size,0);
let first=memo.read(1.125,2.125);
assert.equal(evaluations,1,'non-static gameplay must use original height function');
memo.activate(true);
assert.equal(memo.read(1.125,2.125),first);
assert.equal(memo.read(1.125,2.125),first);
assert.equal(evaluations,2,'one exact static miss and one exact static hit');
assert.equal(memo.audit().hits,1);
assert.equal(memo.audit().size,1);
const x=0.1+0.2;
memo.read(x,3.75);memo.read(0.3,3.75);
assert.notEqual(x,0.3,'test requires two distinct exact floating coordinates');
assert.equal(memo.audit().size,3,'no coordinate quantization');
const beforeHits=evaluations;
memo.read(x,3.75);memo.read(0.3,3.75);
assert.equal(evaluations,beforeHits,'each distinct floating coordinate must hit its own lane');
const noCacheBefore=evaluations;
memo.activate(false);memo.read(x,3.75);
assert.equal(evaluations,noCacheBefore+1,'runtime simulation bypasses memo');
memo.activate(true);
assert.equal(memo.override(false),false);
assert.equal(memo.audit().enabled,false);
assert.equal(memo.override(null),true);
let count=0;
const stress=factory((a,b)=>{count++;return a*.75+b*.25});
stress.activate(true);
for(let i=0;i<32778;i++)assert.equal(stress.read(i,1.375),i*.75+1.375*.25);
let audit=stress.audit();
assert.equal(audit.size,32768,'finite bound must hold after real cold-scene growth');
assert.equal(audit.xRows,32768);
assert.equal(audit.clears,0,'never flush every live height at once');
assert.equal(audit.evictedRows,10,'evict oldest spatial lane, not all lanes');
assert.equal(audit.fullFlushOnCapacity,false);
assert.equal(audit.exactNumericCoordinateKeys,true);
const repeated=count;
stress.read(32777,1.375);
assert.equal(count,repeated,'latest exact spatial height must remain resident');
stress.read(0,1.375);
assert.equal(count,repeated+1,'evicted oldest height must recompute exactly');
assert.equal(stress.audit().size,32768);
assert.equal(stress.audit().changesNavigation,false);
assert.equal(stress.audit().changesAuthority,false);
assert.equal(stress.read(Infinity,2),Infinity,'nonfinite height queries preserve raw fallback');
console.log('W456 original-world renderer numeric spatial lanes preserve exact terrain, bounded 32768 pairs, row eviction without full cache cliff; production JS syntax PASS. No hardware FPS/visual milestone claimed.');
