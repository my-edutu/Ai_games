'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const html=fs.readFileSync('public/tiny-kingdom/index.html','utf8');
const script=html.slice(html.indexOf('<script>')+8,html.lastIndexOf('</script>'));
new vm.Script(script,{filename:'shipped-tiny-kingdom-inline.js'});
const begin=script.indexOf('function residentStreetAtlasSignature(');
const end=script.indexOf('function rebuildGroundAtlas(){',begin);
assert.ok(begin>0&&end>begin,'W381 actual bounded street geometry signature');
const signature=vm.runInNewContext('const REAL_HOME_LANE_BUDGET=3600;\n'+script.slice(begin,end)+'\nresidentStreetAtlasSignature;');
const lanes=[{a:[1,2],b:[3,4],halfWidth:.99},{a:[3,4],b:[4,5],halfWidth:.42}];
const original=JSON.stringify(lanes),old=signature(lanes);
assert.equal(old,signature(JSON.parse(original)),'unchanged real road must reuse material');
assert.notEqual(old,signature(lanes.slice().reverse()),'reorder invalidation');
assert.notEqual(old,signature([{a:[1,2],b:[3.01,4],halfWidth:.99},lanes[1]]),'physical move invalidation');
assert.notEqual(old,signature([{a:[1,2],b:[3,4],halfWidth:.98},lanes[1]]),'width invalidation');
assert.equal(JSON.stringify(lanes),original,'material cannot modify original paths');
assert.throws(()=>signature(Array.from({length:601},()=>lanes[0])),/finite atlas/);
assert.throws(()=>signature([{a:[NaN,1],b:[2,3],halfWidth:.5}]),/invalid authentic/);
assert.throws(()=>signature([{a:[0,1],b:[2,3],halfWidth:2}]),/invalid authentic/);
const comp=script.slice(script.indexOf('function rebuildGroundAtlas(){'),
 script.indexOf('if(gpuAvailable){\n gl.uniform1i(uniforms.groundAtlas',end));
assert.match(comp,/liveStreetKey=residentStreetAtlasSignature\(realHomeLaneSections\)/);
assert.match(comp,/if\(liveStreetKey!==groundAtlasStreetKey\)\{/);
assert.match(comp,/streetCtx.clearRect\(0,0,size,size\)/);
assert.match(comp,/paintRealResidentStreetAlbedo\(\s*streetCtx/);
assert.match(comp,/ctx.drawImage\(groundAtlasStreetCanvas,0,0\)/);
assert.doesNotMatch(comp,/paintRealResidentStreetAlbedo\(\s*ctx,/);
assert.match(comp,/planGroundAtlasDirtyRegions\(groundAtlasPriorPixels,composite/);
assert.match(comp,/gl.texSubImage2D\(gl.TEXTURE_2D,0,/);
assert.match(comp,/physicalStreetOverlayReuses:groundAtlasStreetReuses/);
assert.match(comp,/groundAtlasHomeRoadAudit.matchedSource=/);
console.log('W381 PASS: real inhabited lanes, exact topology invalidation, bounded original resident overlay and retained GPU sparse uploads; no hardware FPS claim');
