'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { pathToFileURL } = require('node:url');

const actorSource = fs.readFileSync(path.resolve(__dirname, '../../public/ai-maze-escape/characters.js'), 'utf8');
const threeUrl = pathToFileURL(path.resolve(__dirname, '../../node_modules/three/build/three.module.js')).href;

test('Pip and Thornback reuse length-independent cylinders without a silhouette or normal regression', async () => {
  const THREE = await import(threeUrl);
  // Compare the exact physical surface and normals generated by installed
  // Three, not a source-only approximation. A unit rod scaled along Y must
  // produce the SAME modeled rod as the previously unique height geometry.
  for (const radial of [8, 16]) {
    for (const [bottom, top, height] of [
      [.025, .025, .492], [.045, .045, .055],
      [.070, .070, .644], [.063, 0, .15], [.11, .07, .045]
    ]) {
      const legacy = new THREE.CylinderGeometry(top, bottom, height, radial);
      const pooled = new THREE.CylinderGeometry(top, bottom, 1, radial);
      pooled.scale(1, height, 1);
      for (const name of ['position', 'normal']) {
        const expected = legacy.getAttribute(name), actual = pooled.getAttribute(name);
        assert.equal(actual.count, expected.count, name + ' vertex count');
        for (let i = 0; i < expected.array.length; i++)
          assert.ok(Math.abs(expected.array[i] - actual.array[i]) < 1e-5,
            name + ' component ' + i + ' at height ' + height);
      }
      legacy.dispose(); pooled.dispose();
    }
  }
  assert.match(actorSource, /geometry\(`c\$\{radius\},\$\{top\}`/);
  assert.match(actorSource, /new THREE\.CylinderGeometry\(top,radius,1,radial\)/);
  assert.match(actorSource, /object\.scale\.y = length;/);
});

test('both actor quality levels keep the pooled primitive ownership and final release semantics', async () => {
  const source = actorSource.replace("'./vendor/three.module.js'", JSON.stringify(threeUrl));
  const { createExplorer, createWarden, rigPrimitiveResourceStats } =
    await import('data:text/javascript;base64,' + Buffer.from(source).toString('base64'));
  const starting = rigPrimitiveResourceStats();
  for (const balanced of [false, true]) {
    const pip = createExplorer({balanced});
    const thornback = createWarden({balanced});
    assert.ok(rigPrimitiveResourceStats().unique > starting.unique,
      'real detailed actors must own pooled GPU primitives');
    for (const actor of [pip, thornback]) {
      actor.update({moving: true, time: .5, delta: 1/60, heading: Math.PI/3});
      actor.group.traverse(part => {
        if (part.isMesh && part.geometry?.type === 'CylinderGeometry') {
          assert.equal(part.geometry.parameters.height, 1,
            'independently articulated physical rod uses a unit-height shared shape');
          assert.ok(part.scale.y > 0 && Number.isFinite(part.scale.y),
            'real physical rod length is a nonzero mesh transform');
        }
      });
    }
    pip.dispose(); pip.dispose();
    thornback.update({moving: true, time: 1, delta: 1/60});
    thornback.dispose(); thornback.dispose();
    assert.deepEqual(rigPrimitiveResourceStats(), starting,
      'after the last actor releases ownership there is no pooled resource leak');
  }
});
