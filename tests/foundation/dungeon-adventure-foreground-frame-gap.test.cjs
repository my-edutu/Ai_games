'use strict';
const {test}=require('node:test'),assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'../..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const source='public/ai-dungeon/foreground-recession.js';
const load=()=>import('data:text/javascript;base64,'+Buffer.from(read(source)).toString('base64'));
const prop=()=>({position:{y:0},visible:true,userData:{}});
const volume=[-.3,0,-.3,.3,3.2,.3];
test('sparse real frame delivery never animates architecture rising across several seconds',async()=>{
 const {applyForegroundRecession:apply}=await load(),g=prop();
 apply(g,false,.016,false,volume);
 apply(g,true,.05,false,volume);
 assert.ok(g.position.y<0&&g.position.y>-3.6,'normal-frame recession remains smooth');
 apply(g,false,.05,false,volume);
 assert.ok(g.position.y<0&&g.position.y>-3.6,'normal-frame return is still eased');
 apply(g,false,.05,false,volume,true);
 assert.equal(g.position.y,0,'slow-delivery frame must restore base height in one rendered frame');
 assert.equal(g.visible,true);
 apply(g,true,.05,false,volume,true);
 assert.equal(g.visible,false,'a real blocking stone is removed rather than drifting halfway under floor');
 assert.equal(g.position.y,-3.52);
 apply(g,false,.05,false,volume,true);
 assert.equal(g.position.y,0);
 assert.equal(g.userData.dungeonForegroundRecession.baseY,0);
});
test('frame-gap fallback stays camera-only, constant-size and respects reduced-motion',async()=>{
 const {applyForegroundRecession:apply}=await load(),g=prop();
 assert.equal(apply(g,true,.016,true,volume,true),true);
 assert.equal(g.visible,false);
 assert.equal(apply(g,false,.016,true,volume,false),false);
 assert.equal(g.visible,true);
 assert.ok(Object.keys(g.userData.dungeonForegroundRecession).length<=3);
 const app=read('public/ai-dungeon/app.js');
 const environment=read('public/ai-dungeon/environment.js');
 assert.match(app,/const slowFrame=frameInterval>\.25/);
 assert.match(app,/applyForegroundRecession\(group,hidden\|\|portrait,frameDt,reduced,[^\n]+,slowFrame\)/);
 assert.match(app,/applyForegroundRecession\(prop,blocked,dt,reduced,[^\n]+,slowFrame\)/);
 assert.match(environment,/applyForegroundRecession\(group,blocked\|\|portrait,frameDt,reducedMotion,[^\n]+,slowFrame\)/);
 assert.match(app,/world\.userData\.dressing\?\.cutaway\([^;]+dt,reduced,slowFrame\)/);
});
